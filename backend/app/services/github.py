"""GitHub credential encryption and API helpers."""

import base64
import re
import secrets
import urllib.error
import urllib.parse
import urllib.request

from cryptography.hazmat.primitives.ciphers.aead import AESGCM

from ..core.config import GITHUB_CREDENTIALS_KEY
from ..core.db import connection

_TOKEN_SETTING = "github_token_encrypted"
_AAD = b"arfeen-cloud/github-token/v1"
_API = "https://api.github.com"
_API_VERSION = "2022-11-28"


class GitHubError(Exception):
    """Safe, user-facing GitHub integration error."""


def _encryption_key() -> bytes:
    if not GITHUB_CREDENTIALS_KEY:
        raise GitHubError("GitHub credential encryption is not configured. Set GITHUB_CREDENTIALS_KEY and restart the stack.")
    try:
        key = base64.urlsafe_b64decode(GITHUB_CREDENTIALS_KEY.encode("ascii"))
    except (ValueError, UnicodeError) as exc:
        raise GitHubError("GITHUB_CREDENTIALS_KEY is invalid. Keep the original key generated by the installer.") from exc
    if len(key) != 32:
        raise GitHubError("GITHUB_CREDENTIALS_KEY must decode to exactly 32 bytes.")
    return key


def encrypt_github_token(token: str) -> str:
    nonce = secrets.token_bytes(12)
    ciphertext = AESGCM(_encryption_key()).encrypt(nonce, token.encode("utf-8"), _AAD)
    return "v1." + base64.urlsafe_b64encode(nonce + ciphertext).decode("ascii")


def decrypt_github_token(ciphertext: str) -> str:
    if not ciphertext.startswith("v1."):
        raise GitHubError("The saved GitHub credential has an unsupported format. Reconnect GitHub in Settings.")
    try:
        payload = base64.urlsafe_b64decode(ciphertext[3:].encode("ascii"))
        nonce, encrypted = payload[:12], payload[12:]
        if len(nonce) != 12 or len(encrypted) < 16:
            raise ValueError("invalid ciphertext length")
        return AESGCM(_encryption_key()).decrypt(nonce, encrypted, _AAD).decode("utf-8")
    except GitHubError:
        raise
    except Exception as exc:
        raise GitHubError("Could not decrypt the saved GitHub credential. Check GITHUB_CREDENTIALS_KEY and reconnect GitHub if needed.") from exc


def github_token() -> str | None:
    with connection() as db:
        row = db.execute("SELECT value FROM settings WHERE key=?", (_TOKEN_SETTING,)).fetchone()
    return decrypt_github_token(row["value"]) if row else None


def save_github_token(token: str) -> None:
    encrypted = encrypt_github_token(token)
    with connection() as db:
        db.execute(
            "INSERT INTO settings(key,value) VALUES(?,?) ON CONFLICT(key) DO UPDATE SET value=excluded.value",
            (_TOKEN_SETTING, encrypted),
        )


def delete_github_token() -> None:
    with connection() as db:
        db.execute("DELETE FROM settings WHERE key=?", (_TOKEN_SETTING,))


def _github_get(token: str, path: str):
    request = urllib.request.Request(
        f"{_API}/{path.lstrip('/')}",
        headers={
            "Accept": "application/vnd.github+json",
            "Authorization": f"Bearer {token}",
            "X-GitHub-Api-Version": _API_VERSION,
            "User-Agent": "Arfeen-Cloud",
        },
    )
    try:
        class SameHostRedirect(urllib.request.HTTPRedirectHandler):
            def redirect_request(self, req, fp, code, msg, headers, newurl):
                if urllib.parse.urlparse(newurl).hostname != "api.github.com":
                    raise urllib.error.URLError("Refusing GitHub API redirect to another host")
                return super().redirect_request(req, fp, code, msg, headers, newurl)

        opener = urllib.request.build_opener(SameHostRedirect())
        with opener.open(request, timeout=20) as response:
            import json

            return json.loads(response.read(5 * 1024 * 1024))
    except urllib.error.HTTPError as exc:
        if exc.code == 401:
            raise GitHubError("GitHub rejected this token. Check that it is active and try again.") from exc
        if exc.code == 403:
            raise GitHubError("GitHub denied access. Check repository permissions and any organization approval requirement.") from exc
        if exc.code == 404:
            raise GitHubError("GitHub could not find that repository or branch, or the token cannot access it.") from exc
        if exc.code == 422:
            raise GitHubError("GitHub rejected the request. Check the repository details and token permissions.") from exc
        raise GitHubError(f"GitHub API request failed with HTTP {exc.code}.") from exc
    except (urllib.error.URLError, TimeoutError) as exc:
        raise GitHubError("Could not reach GitHub. Check the server's internet connection and try again.") from exc
    except ValueError as exc:
        raise GitHubError("GitHub returned an invalid API response.") from exc


def validate_github_token(token: str) -> None:
    query = urllib.parse.urlencode({
        "visibility": "all",
        "affiliation": "owner,collaborator,organization_member",
        "per_page": 1,
        "page": 1,
    })
    result = _github_get(token, f"user/repos?{query}")
    if not isinstance(result, list):
        raise GitHubError("GitHub returned an invalid repository response.")


def list_repositories(token: str):
    repositories = []
    for page in range(1, 11):
        query = urllib.parse.urlencode({
            "visibility": "all",
            "affiliation": "owner,collaborator,organization_member",
            "sort": "full_name",
            "per_page": 100,
            "page": page,
        })
        items = _github_get(token, f"user/repos?{query}")
        if not isinstance(items, list):
            raise GitHubError("GitHub returned an invalid repository list.")
        for item in items:
            owner = item.get("owner", {}).get("login", "")
            name = item.get("name", "")
            if owner and name:
                repositories.append({
                    "owner": owner,
                    "name": name,
                    "full_name": item.get("full_name", f"{owner}/{name}"),
                    "private": bool(item.get("private")),
                    "default_branch": item.get("default_branch") or "main",
                })
        if len(items) < 100:
            break
    return repositories


def list_branches(token: str, owner: str, repo: str):
    segment = re.compile(r"^[A-Za-z0-9_.-]{1,100}$")
    if not segment.fullmatch(owner) or not segment.fullmatch(repo):
        raise GitHubError("Invalid GitHub owner or repository name.")
    branches = []
    quoted_owner = urllib.parse.quote(owner, safe="")
    quoted_repo = urllib.parse.quote(repo, safe="")
    for page in range(1, 11):
        query = urllib.parse.urlencode({"per_page": 100, "page": page})
        items = _github_get(token, f"repos/{quoted_owner}/{quoted_repo}/branches?{query}")
        if not isinstance(items, list):
            raise GitHubError("GitHub returned an invalid branch list.")
        for item in items:
            name = item.get("name")
            if isinstance(name, str) and name:
                branches.append({"name": name, "sha": item.get("commit", {}).get("sha", "")})
        if len(items) < 100:
            break
    return branches
